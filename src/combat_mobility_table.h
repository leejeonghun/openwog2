inline int mobility_selector_for_class(int combat_class, int flags14) {
    if (combat_class < 0 || combat_class >= kMobilitySelectorCount) return -1;
    int sel = (int)kMobilitySelectorTable[combat_class];
    if (sel == 5 && ((flags14 & 1) == 0)) sel = 0;
    if (sel < 0 || sel >= kMobilityGridCount) return -1;
    return sel;
}
